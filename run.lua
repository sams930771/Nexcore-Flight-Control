package.path = "src/?.lua;tests/?.lua;" .. package.path
local harness = require("cc_mock")
local cal = require("nexcore.calibration")
local app = require("nexcore.app")
local originalPrint=print
local count=0
local function test(name, fn)
  fn(); count=count+1; originalPrint("PASS "..name)
end
local function run(options, events)
  local mock=harness.setup(options)
  local c=dofile("config/default.lua")
  for _,event in ipairs(events or {}) do mock.event(event[1],event[2],event[3],event[4]) end
  -- Silence the cockpit's final shell messages only.
  print=function() end
  local ok,s=pcall(app.run,"mock",c)
  print=originalPrint
  assert(ok,s)
  return mock,s
end
local function key(t,name) return {t,"key",keys[name]} end
local function writes(mock)
  local found={}; for _,call in ipairs(mock.calls) do if call.method=="setScrollValue" then found[#found+1]=call end end
  return found
end
-- keys are established once before constructing event tables; each setup uses the same codes.
harness.setup()
test("original calibration and nearest integer GO",function()
  local c=dofile("config/default.lua"); cal.validate(c)
  for _,point in ipairs(c.calibration) do assert(cal.altitude(c.calibration,point.power)==point.altitude) end
  assert(cal.power(c,176.489)==44 and cal.power(c,10000)==48)
end)
test("Q retains live power and outputs",function()
  local m,s=run(nil,{key(2,"q")})
  assert(s.exit=="hands_off" and s.power==43 and #writes(m)==0)
  assert(m.powers.left==43 and m.powers.right==43 and m.outputs.left and m.outputs.right)
  assert(s.samples>=7 and s.loops>=7)
end)
test("X disables outputs and retains scroll values",function()
  local m,s=run(nil,{key(1,"x")})
  assert(s.exit=="off" and s.offOK and not m.outputs.left and not m.outputs.right)
  assert(m.powers.left==43 and #writes(m)==0)
end)
test("target editing cannot consume telemetry timers",function()
  local m,s=run(nil,{key(.3,"t"),{.4,"paste","176.489"},key(3,"enter"),key(3.5,"q")})
  assert(s.target==176.489 and not s.editing and s.samples>=13 and s.loops>=13)
  assert(#writes(m)==0)
end)
test("GO single command, HOLD power, MANUAL +/- one unit",function()
  local m,s=run(nil,{key(.3,"t"),{.4,"paste","176.489"},key(.5,"enter"),key(.6,"g"),key(1,"h"),key(1.2,"m"),key(1.4,"minus"),key(2,"q")})
  local w=writes(m)
  assert(#w==4 and w[1].value==44 and w[2].value==44 and w[3].value==43 and w[4].value==43)
  assert(s.mode=="MANUAL" and s.power==43 and s.samples>=7)
end)
test("delayed sensor cannot freeze UI, target entry or Q",function()
  local _,s=run({sensorDelay=5},{key(.3,"t"),{.4,"paste","180"},key(.5,"enter"),key(.8,"q")})
  assert(s.exit=="hands_off" and s.target==180 and s.samples==0 and s.loops>=3)
end)
test("sensor errors recover without killing workers",function()
  local _,s=run({sensorError=2},{key(2,"q")})
  assert(s.failures==2 and s.samples>=5 and s.loops>=7)
end)
test("unchanged altitude is fresh sampling, not a frozen worker",function()
  local _,s=run({constantAltitude=170.7356},{key(3,"q")})
  assert(s.samples>=11 and s.changes==0 and s.sampleAt>=2500 and s.changeAt==0)
end)
test("worker exception is logged and restarted",function()
  local m,s=run({crashScan=true},{key(2,"q")})
  assert(s.workerErrors.burner==1 and s.ready and s.samples>=7)
  local found=false; for _,r in ipairs(m.logs) do if r.kind=="worker_restart" then found=true end end
  assert(found,"Missing worker restart diagnostic")
end)
test("UI exception restarts without stopping sensor",function()
  local _,s=run({crashUI=true},{key(2,"q")})
  assert(s.workerErrors.ui==1 and s.samples>=7 and s.exit=="hands_off")
end)
test("partial burner failure stops further writes and requires D",function()
  local m,s=run({failWriteSide="right"},{key(.5,"equals"),key(1,"equals"),key(2,"q")})
  assert(#writes(m)==2 and not s.ready and s.mode=="MANUAL")
  assert(m.powers.left==44 and m.powers.right==43)
end)
test("D inventories readbacks without changing power",function()
  local m,s=run(nil,{key(.5,"d"),key(1.5,"q")})
  assert(#writes(m)==0 and s.ready and s.samples>=5)
end)
test("Q and X remain active during target input",function()
  local m,s=run(nil,{key(.3,"t"),key(.5,"x")})
  assert(s.exit=="off" and not m.outputs.left)
  local _,q=run(nil,{key(.3,"t"),key(.5,"q")}); assert(q.exit=="hands_off")
end)
test("terminate preserves outputs",function()
  local m,s=run(nil,{{1,"terminate"}})
  assert(s.exit=="hands_off" and m.outputs.left and m.outputs.right)
end)
test("disk failure remains visible and does not stop telemetry",function()
  local _,s=run({logFailure=true},{key(2,"q")})
  assert(s.logError and s.samples>=7 and s.loops>=7)
end)
test("mismatched startup power is observed without overwriting",function()
  local m,s=run({powers={left=43,right=44}},{key(1,"q")})
  assert(s.mismatch and #writes(m)==0 and m.powers.right==44)
end)
test("X exits while sensor is blocked",function()
  local m,s=run({sensorDelay=5},{key(.8,"x")})
  assert(s.exit=="off" and s.samples==0 and not m.outputs.left and not m.outputs.right)
end)
test("GO is blocked without fresh sensor data",function()
  local m,s=run({sensorDelay=5},{key(.2,"t"),{.3,"paste","180"},key(.4,"enter"),key(.5,"g"),key(1,"q")})
  assert(#writes(m)==0 and s.mode=="MANUAL" and s.target==180)
end)
test("pending burner call cannot block X",function()
  local m,s=run({setterDelay=5},{key(.3,"equals"),key(.8,"x")})
  assert(s.exit=="off" and #writes(m)==1 and not m.outputs.left and not m.outputs.right)
end)
test("manual integer limits stay within zero through 500",function()
  local m,s=run({powers={left=500,right=500}},{key(.3,"equals"),key(.8,"q")})
  assert(s.power==500 and writes(m)[1].value==500)
  local low,q=run({powers={left=0,right=0}},{key(.3,"minus"),key(.8,"q")})
  assert(q.power==0 and writes(low)[1].value==0)
end)
test("exit keys work during worker restart backoff",function()
  local m,s=run({crashUI=true},{key(.5,"x")})
  assert(s.workerErrors.ui==1 and s.exit=="off" and not m.outputs.left)
end)
originalPrint("Passed "..count.." behavior tests")
dofile("tests/install.lua")
